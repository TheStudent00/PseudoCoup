import z3                                                   # noqa: E402
import lean_reader as LR                                    # noqa: E402
import assemble as AS                                       # noqa: E402

EMIT_DIR = os.path.join(HERE, "lean_emit")
AXIOM = re.compile(r"^axiom\s+([A-Za-z_][A-Za-z0-9_']*)\s*:\s*(.*?)\s*$")
X_REGISTER = re.compile(r"^x(\d+)$")
F_REGISTER = re.compile(r"^f(\d+)$")


class LiftRefused(Exception):
    """the generated lifter refuses this line, and says why."""


def unit_axioms(directory):
    """the names the emit declares as axioms (the platform's externs)
    whose result is the unit type: each is a no-op for this walk."""
    out = []
    for root, _dirs, files in os.walk(directory):
        for name in sorted(files):
            if not (name.endswith(".lean") or name.endswith(".lean.gz")):
                continue
            for line in LR.open_lean_file(os.path.join(root, name)):
                hit = AXIOM.match(line)
                if hit is None:
                    continue
                typetext = hit.group(2).replace(" ", "")
                if typetext.endswith("SailMUnit") or typetext.endswith("→Unit") \
                        or typetext == "Unit":
                    out.append(hit.group(1))
    return out


def no_op(*_args):
    return None


class BridgedMachine(LR.Machine):
    """the reader's machine whose x and f registers ARE the walk's
    MachineState; every other register is its own."""

    def __init__(self, widths, state, initial):
        LR.Machine.__init__(self, widths, initial)
        self.state = state

    def read(self, name, width=None):
        """an x or f register not yet in this machine's overlay is read from
        the walk's state and kept here; a write stays in the overlay until
        the lifter commits it after the instruction (so a conditional's
        branches merge before anything reaches the state)."""
        if name in self.registers:
            self.reads.append(name)
            return self.registers[name]
        hit = X_REGISTER.match(name)
        if hit is not None:
            value = self.state.read_register(int(hit.group(1)))
            self.registers[name] = value
            self.reads.append(name)
            return value
        hit = F_REGISTER.match(name)
        if hit is not None:
            value = self.state.read_float(int(hit.group(1)))
            self.registers[name] = value
            self.reads.append(name)
            return value
        return LR.Machine.read(self, name, width)

    def commit(self):
        """every x or f register written in this machine, into the state."""
        written = set(name for name, _value in self.writes)
        for name in written:
            value = self.registers.get(name)
            if value is None:
                continue
            hit = X_REGISTER.match(name)
            if hit is not None:
                self.state.write_register(int(hit.group(1)), LR.bv_of(value))
                continue
            hit = F_REGISTER.match(name)
            if hit is not None:
                self.state.write_float(int(hit.group(1)), LR.bv_of(value))


class GeneratedLifter(object):
    """the emit, parsed once; the model's reset, run once; then lines."""

    def __init__(self, emit_dir=EMIT_DIR, work=None):
        self.emit_dir = emit_dir
        commit_file = os.path.join(emit_dir, "SAIL_MODEL_COMMIT.txt")
        self.commit = None
        if os.path.exists(commit_file):
            self.commit = open(commit_file).read().strip()
        self.definitions, self.origin = LR.parse_emit(emit_dir)
        self.widths = LR.register_widths(emit_dir)
        self.axioms = unit_axioms(emit_dir)
        for name in self.axioms:
            LR.PRIMITIVES[name] = no_op
        self.reader = LR.Reader(self.definitions, self.widths)
        self.work = work or os.environ.get("SL1_WORK", "/tmp/sl1_lifter")
        self.decoded = {}
        self.assembled = {}
        self.reset_registers, self.reset_report = self.reset()
        self.reset_registers, self.prologue_report = self.prologue()

    # -- the model's own reset -------------------------------------------

    def reset(self):
        """the registers the model's own reset leaves, as far as the
        reader can run it: `reset` first, then its pieces."""
        report = []
        for name in ("reset",):
            if name not in self.definitions:
                report.append("%s: no such definition" % name)
                continue
            machine = LR.Machine(self.widths)
            skipped = []
            self.reader.call_tolerant(name, [None], machine, skipped)
            report.append("%s: evaluated statement by statement, %d "
                          "register writes, %d statements skipped"
                          % (name, len(machine.writes), len(skipped)))
            for item in skipped:
                report.append("  skipped: %s" % item[:220])
            for piece in ("reset_sys", "reset_misa"):
                if piece in self.definitions and not any(
                        w[0] == "cur_privilege" for w in machine.writes):
                    sub_skipped = []
                    self.reader.call_tolerant(piece, [None], machine, sub_skipped)
                    report.append("%s: run tolerantly as well, %d skipped"
                                  % (piece, len(sub_skipped)))
                    for item in sub_skipped:
                        report.append("  skipped: %s" % item[:220])
            registers = {}
            for register, value in machine.registers.items():
                if LR.z3.is_bv(value) or LR.z3.is_bool(value) or \
                        isinstance(value, (LR.LInt, LR.Ctor, dict, tuple)):
                    registers[register] = value
            return registers, report
        return {}, report

    # -- the state a walked body starts from -------------------------------

    PROLOGUE = ["lui t0, 0x6", "csrrs zero, mstatus, t0"]
    """the two instructions the point-check harness runs before any float
    instruction (`sail_points.PROGRAM_FLOAT`: at reset the float unit is
    OFF, `mstatus.FS` = Off, and every float instruction is then illegal;
    a walked body sits inside a running program where it is on).  They
    are run through the model itself, so the state they leave is the
    model's own; `lui t0, 0x6` places 0x6000 in t0."""

    def prologue(self):
        """the reset state after the harness prologue, run by the model."""
        report = []
        import riscv_reference as RV                        # noqa: E402
        state = RV.MachineState({})
        registers = dict(self.reset_registers)
        try:
            words = self.words_of_lines(self.PROLOGUE)
            for line, (word, size) in zip(self.PROLOGUE, words):
                instr = self.decode(word, size)
                machine = BridgedMachine(self.widths, state, dict(registers))
                result = self.reader.call("execute", [instr], machine)
                if isinstance(result, LR.Ctor) and result.name == "ExecuteAs":
                    result = self.reader.call("execute", [result.args[0]], machine)
                registers = dict(machine.registers)
                report.append("%s: %s, mstatus = %s" % (
                    line, constructor_name(result),
                    z3.simplify(registers["mstatus"]) if "mstatus" in registers else "?"))
        except (LiftRefused, LR.ReadRefused) as problem:
            report.append("PROLOGUE REFUSED: %s" % ("%s" % problem)[:300])
            return self.reset_registers, report
        for name in [k for k in registers if X_REGISTER.match(k)]:
            del registers[name]
        return registers, report

    # -- words ----------------------------------------------------------

    def words_of_lines(self, lines):
        key = tuple(lines)
        if key in self.assembled:
            return self.assembled[key]
        try:
            words = AS.words_of(lines, self.work)
        except AS.AssemblyRefused as problem:
            raise LiftRefused("ASSEMBLY_REFUSED: %s" % ("%s" % problem)[:400])
        if len(words) != len(lines):
            raise LiftRefused("ASSEMBLY_COUNT: %d lines assembled to %d "
                              "words" % (len(lines), len(words)))
        self.assembled[key] = words
        return words

    # -- decode ---------------------------------------------------------

    def decode(self, word, size):
        key = (word, size)
        if key in self.decoded:
            return self.decoded[key]
        machine = LR.Machine(self.widths, dict(self.reset_registers))
        try:
            if size == 4:
                instr = self.reader.call("encdec_backwards",
                                         [z3.BitVecVal(word, 32)], machine)
            else:
                instr = self.reader.call("encdec_compressed_backwards",
                                         [z3.BitVecVal(word, 16)], machine)
        except LR.ReadRefused as problem:
            raise LiftRefused("DECODE_REFUSED for word 0x%x: %s"
                              % (word, ("%s" % problem)[:300]))
        self.decoded[key] = instr
        return instr

    # -- execute --------------------------------------------------------

    def execute(self, instr, state):
        machine = BridgedMachine(self.widths, state,
                                 dict(self.reset_registers))
        try:
            result = self.reader.call("execute", [instr], machine)
            if isinstance(result, LR.Ctor) and result.name == "ExecuteAs":
                result = self.reader.call("execute", [result.args[0]],
                                          machine)
        except LR.ReadRefused as problem:
            raise LiftRefused("EXECUTE_REFUSED for %s: %s"
                              % (constructor_name(instr),
                                 ("%s" % problem)[:300]))
        machine.commit()
        return result, machine

    def lift_line(self, line, state):
        words = self.words_of_lines([line])
        word, size = words[0]
        instr = self.decode(word, size)
        return self.execute(instr, state)


def constructor_name(instr):
    if isinstance(instr, LR.Ctor):
        return instr.name
    return "%r" % (instr,)


_LIFTER = [None]


def shared_lifter():
    """one lifter per process: the emit parsed and the reset run once."""
    if _LIFTER[0] is None:
        _LIFTER[0] = GeneratedLifter()
    return _LIFTER[0]
